/* =========================================================
   SYSTÈME I18N — BlockWeb Master
   ─────────────────────────────────────────────────────────
   Langues supportées : fr (défaut), en
   Détection : navigator.language → langue du navigateur
   Fallback  : 'en' si la langue n'est pas supportée
========================================================= */

export type Locale = 'fr' | 'en'

export const SUPPORTED_LOCALES: Locale[] = ['fr', 'en']

/* ── Détection automatique de la langue ── */
export function detectLocale(): Locale {
    const lang = (navigator.language ?? 'en').toLowerCase().slice(0, 2)
    return SUPPORTED_LOCALES.includes(lang as Locale) ? (lang as Locale) : 'en'
}

